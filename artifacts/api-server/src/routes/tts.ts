/**
 * tts.ts — ElevenLabs Text-to-Speech Route
 *
 * Provides two endpoints:
 *   GET  /api/voices      — Returns the list of available ElevenLabs voices.
 *   POST /api/tts/stream  — Accepts { textToSpeak, selectedVoiceId } and
 *                           streams back audio/mpeg from ElevenLabs.
 *
 * The API key is read exclusively from the ELEVENLABS_API_KEY environment
 * variable.  Never hardcode the key here.
 */

import { Router, type IRouter, type Request, type Response } from "express";

const router: IRouter = Router();

// --------------------------------------------------------------------------
// Helpers
// --------------------------------------------------------------------------

/**
 * Reads and validates the ElevenLabs API key from environment variables.
 * Throws a descriptive error when the key is missing so the caller can
 * surface a clear 503 to the client.
 */
function getElevenLabsKey(): string {
  const key = process.env["ELEVENLABS_API_KEY"];
  if (!key || key === "your_api_key_here" || key.trim() === "") {
    throw new Error(
      "ELEVENLABS_API_KEY is not configured.  " +
        "Add it to your environment variables or .env file.",
    );
  }
  return key.trim();
}

/** Base URL for the ElevenLabs v1 REST API. */
const ELEVENLABS_BASE = "https://api.elevenlabs.io/v1";

// --------------------------------------------------------------------------
// GET /api/voices
// --------------------------------------------------------------------------

/**
 * Returns the list of voices available for the configured ElevenLabs account.
 * The frontend uses this to populate a voice-selection dropdown.
 *
 * Response shape (subset of ElevenLabs API):
 *   { voices: Array<{ voice_id: string; name: string; category: string }> }
 */
router.get("/voices", async (req: Request, res: Response) => {
  let key: string;
  try {
    key = getElevenLabsKey();
  } catch (err) {
    req.log?.warn({ err }, "ElevenLabs key not configured");
    res.status(503).json({ error: (err as Error).message });
    return;
  }

  try {
    const response = await fetch(`${ELEVENLABS_BASE}/voices`, {
      headers: {
        "xi-api-key": key,
        Accept: "application/json",
      },
    });

    if (!response.ok) {
      const body = await response.text();
      req.log?.error({ status: response.status, body }, "ElevenLabs voices error");
      res.status(response.status).json({ error: `ElevenLabs API error: ${body.slice(0, 200)}` });
      return;
    }

    // Forward only the relevant fields to keep the payload small
    const data = (await response.json()) as {
      voices: Array<{
        voice_id: string;
        name: string;
        category?: string;
        labels?: Record<string, string>;
        preview_url?: string;
      }>;
    };

    const voices = (data.voices ?? []).map((v) => ({
      voice_id: v.voice_id,
      name: v.name,
      category: v.category ?? "generated",
      accent: v.labels?.["accent"] ?? "",
      description: v.labels?.["description"] ?? "",
      preview_url: v.preview_url ?? "",
    }));

    res.json({ voices });
  } catch (err) {
    req.log?.error({ err }, "Failed to fetch ElevenLabs voices");
    res.status(502).json({ error: "Failed to fetch voices from ElevenLabs." });
  }
});

// --------------------------------------------------------------------------
// POST /api/tts/stream
// --------------------------------------------------------------------------

/**
 * Streams audio generated by ElevenLabs back to the client.
 *
 * Request body:
 *   {
 *     textToSpeak:     string  — The text to convert to speech.
 *     selectedVoiceId: string  — ElevenLabs voice ID (e.g. "21m00Tcm4TlvDq8ikWAM").
 *   }
 *
 * Response: audio/mpeg binary stream (pipe from ElevenLabs → client).
 */
router.post("/tts/stream", async (req: Request, res: Response) => {
  let key: string;
  try {
    key = getElevenLabsKey();
  } catch (err) {
    req.log?.warn({ err }, "ElevenLabs key not configured");
    res.status(503).json({ error: (err as Error).message });
    return;
  }

  // --- Validate input ---
  const textToSpeak =
    typeof req.body?.textToSpeak === "string" ? req.body.textToSpeak.trim() : "";
  const selectedVoiceId =
    typeof req.body?.selectedVoiceId === "string"
      ? req.body.selectedVoiceId.trim()
      : "";

  if (!textToSpeak) {
    res.status(400).json({ error: "Missing 'textToSpeak' in request body." });
    return;
  }

  // Use a natural-sounding default voice (Rachel — ElevenLabs premade voice)
  // if the caller doesn't specify one.
  const voiceId = selectedVoiceId || "21m00Tcm4TlvDq8ikWAM";

  try {
    // Call the ElevenLabs streaming TTS endpoint
    const ttsResponse = await fetch(
      `${ELEVENLABS_BASE}/text-to-speech/${voiceId}/stream`,
      {
        method: "POST",
        headers: {
          "xi-api-key": key,
          "Content-Type": "application/json",
          Accept: "audio/mpeg",
        },
        body: JSON.stringify({
          text: textToSpeak,
          model_id: "eleven_multilingual_v2", // High-quality multilingual model
          voice_settings: {
            stability: 0.5,        // 0–1: higher = more consistent
            similarity_boost: 0.75, // 0–1: higher = closer to voice clone
            style: 0.0,
            use_speaker_boost: true,
          },
        }),
      },
    );

    if (!ttsResponse.ok) {
      const body = await ttsResponse.text();
      req.log?.error({ status: ttsResponse.status, body }, "ElevenLabs TTS error");
      res
        .status(ttsResponse.status)
        .json({ error: `ElevenLabs TTS error: ${body.slice(0, 300)}` });
      return;
    }

    // Stream the audio bytes directly to the client
    res.setHeader("Content-Type", "audio/mpeg");
    res.setHeader("Transfer-Encoding", "chunked");
    res.setHeader("Cache-Control", "no-cache");

    // Node's fetch returns a Web Streams ReadableStream — pipe it to the response
    if (ttsResponse.body) {
      const reader = ttsResponse.body.getReader();
      const pump = async () => {
        while (true) {
          const { done, value } = await reader.read();
          if (done) break;
          res.write(Buffer.from(value));
        }
        res.end();
      };
      await pump();
    } else {
      res.end();
    }
  } catch (err) {
    req.log?.error({ err }, "ElevenLabs TTS stream failed");
    if (!res.headersSent) {
      res.status(502).json({ error: "TTS streaming failed. Please try again." });
    }
  }
});

export default router;
