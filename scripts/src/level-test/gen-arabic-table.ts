// One-time generator: builds the Arabic presentation-forms + joining-type
// table consumed by level-test-api's certificate renderer (pdf-lib cannot
// shape right-to-left text, so we reshape + reverse manually).
//
// Sources (cached locally by the caller):
//   UnicodeData.txt  → presentation forms whose compatibility decomposition
//                      mentions the base letter (e.g. <medial> 0626)
//   ArabicShaping.txt→ joining types R/D/L/U/C/T per base letter
// Output: artifacts/api-server/src/lib/fonts/arabic-presentation.ts
// Run:
//   pnpm --filter @workspace/scripts exec tsx src/level-test/gen-arabic-table.ts
import { writeFileSync, readFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const TMP = process.env.TEMP || process.env.TMP || "/tmp";
const udPath = path.join(TMP, "UnicodeData.txt");
const shPath = path.join(TMP, "ArabicShaping.txt");
const OUT = path.join(path.dirname(fileURLToPath(import.meta.url)), "../../../artifacts/api-server/src/lib/fonts/arabic-presentation.ts");

// ── careful decode HTML-safe? UnicodeData format: fields separated by ';' ──
const lines = readFileSync(udPath, "utf8").split("\n");

// codepoint → { form: base-or-bases } for presentation chars
// (index codepoint → char for two-codepoint lam-alef decomposition)
const byCode = new Map<string, { name: string; decomp: string }>();
for (const l of lines) {
  const f = l.split(";");
  if (f.length < 5) continue;
  byCode.set(f[0], { name: f[1], decomp: f[5] || "" });
}

// presentation forms map: baseCode → { isol, init, medi, fina }
const KIND_MAP: Record<string, "isol" | "init" | "medi" | "fina"> = {
  isolated: "isol", initial: "init", medial: "medi", final: "fina",
};
const forms: Record<string, Partial<Record<"isol" | "init" | "medi" | "fina", string>>> = {};
// lam-alef ligatures: two-base key → single ligature per form
const lamAlef: Array<{ bases: [string, string]; form: string; kind: string }> = [];

for (const [cp, info] of byCode) {
  const code = parseInt(cp, 16);
  const inPresentation = (code >= 0xFB50 && code <= 0xFDFF) || (code >= 0xFE70 && code <= 0xFEFF);
  if (!inPresentation) continue;
  const d = info.decomp;
  if (!d) continue;
  // forms like "<isolated> 0621" or "<initial> 0644 0627"
  const m = d.match(/^<([a-z]+)>\s+([0-9A-F ]+)$/i);
  if (!m) continue;
  const kind = KIND_MAP[m[1].toLowerCase()];
  if (!kind) continue;
  const bases = m[2].trim().split(/\s+/);
  if (bases.length === 1) {
    forms[bases[0]] = forms[bases[0]] || {};
    forms[bases[0]]![kind] = cp;
  } else if (bases.length === 2) {
    lamAlef.push({ bases: [bases[0], bases[1]], form: cp, kind });
  }
}

// joining types from ArabicShaping.txt
const joinTypes: Record<string, string> = {};
for (const l of readFileSync(shPath, "utf8").split("\n")) {
  if (!l || l.startsWith("#")) continue;
  const f = l.split(";");
  if (f.length < 3) continue;
  joinTypes[f[0].trim()] = f[2].trim()[0]; // R D L U C T
}

const ENT = [...Object.entries(forms)]
  // drop the FE70..FE7F "transparent marks block" entries that duplicate harakat only
  .filter(([k, v]) => Object.keys(v).length > 0)
  .sort((a, b) => parseInt(a[0], 16) - parseInt(b[0], 16));

const hex = (cp?: string) => (cp ? `"0x${cp.toLowerCase().padStart(4, "0")}"` : "undefined");

const ts = `// ─────────────────────────────────────────────────────────────────────────────
// arabic-presentation.ts — GENERATED by scripts/src/level-test/gen-arabic-table.ts
// (source: Unicode UCD UnicodeData.txt + ArabicShaping.txt, latest release)
//
// Lets the certificate renderer shape RTL text without a text engine:
//   FORMS: base letter codepoint → { isol, init, medi, fina } presentation form
//   JOIN:  base letter codepoint → joining type (R/D/L/U/C/T)
//   LAMALEF: [first base, second base, ligature cp, form kind]
// Do not edit by hand.
// ─────────────────────────────────────────────────────────────────────────────
export const FORMS: Record<string, { isol?: string; init?: string; medi?: string; fina?: string }> = {
${ENT.map(([k, v]) => `  0x${k.toLowerCase().padStart(4, "0")}: { isol: ${hex(v.isol)}, init: ${hex(v.init)}, medi: ${hex(v.medi)}, fina: ${hex(v.fina)} },`).join("\n")}
};
export const JOIN: Record<string, string> = {
${Object.entries(joinTypes).map(([k, v]) => `  0x${k.toLowerCase().padStart(4, "0")}: "${v}",`).join("\n")}
};
export const LAMALEF: Array<{ a: number; b: number; cp: number; kind: string }> = [
${lamAlef.map(l => `  { a: 0x${l.bases[0].toLowerCase()}, b: 0x${l.bases[1].toLowerCase()}, cp: 0x${l.form.toLowerCase()}, kind: "${l.kind}" },`).join("\n")}
];
`;

writeFileSync(OUT, ts);
console.log(`forms=${Object.keys(forms).length} join=${Object.keys(joinTypes).length} lam-alef=${lamAlef.length}`);
console.log(OUT);
